package cli

import (
	"os"
	"syscall"
)

// ownedByCurrentUser reports whether the file belongs to the running user.
func ownedByCurrentUser(info os.FileInfo) bool {
	st, ok := info.Sys().(*syscall.Stat_t)
	return ok && int64(st.Uid) == int64(os.Getuid())
}
